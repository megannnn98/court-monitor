# Every dash a text may carry, the non-breaking ones too.
_DASHES = re.compile(r"\s*[—–‐‑-]\s*")
_CITY = re.compile(r"^(?:г\.|город)\s*")


def _fold(name: str) -> str:
    folded = " ".join(name.lower().replace("ё", "е").split())
    return _CITY.sub("", _DASHES.sub("-", folded))


def _spellings() -> dict[str, str]:
    known = {_fold(region): region for region in REGIONS}
    for name in _REPUBLICS:
        # «Крым», «Дагестан»: a republic is as often written without the word.
        if name != "Алтай":
            known[_fold(name)] = f"Республика {name}"
    known.update(_ALIASES)
    return known


_KNOWN = _spellings()


def canonical(name: str) -> str:
    """The subject's one name, or «» for a place that is not one subject of the list."""
    return _KNOWN.get(_fold(name), "")
