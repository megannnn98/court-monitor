def lookup_gender(name: str) -> str | None:
    """Look up the gender of a normalized given name.

    Returns ``"masc"`` or ``"femn"`` if the name is in the dictionary,
    ``None`` if absent or present in both lists.  The lookup is case-insensitive and folds ``ё`` → ``е``.
    """
    normalised = name.lower().replace("ё", "е")
    if normalised in MALE_NAMES and normalised in FEMALE_NAMES:
        return None
    if normalised in MALE_NAMES:
        return "masc"
    if normalised in FEMALE_NAMES:
        return "femn"
    return None
