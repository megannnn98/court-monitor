import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

/** The legacy console's stylesheet, for the pieces of legacy pages the React console
 * shows as the server renders them (`LegacyHtml`): every rule under `.legacy-html`, so it
 * styles those pieces and nothing of the console around them.
 *
 * - `:root` becomes the scope itself: the legacy variables (`--muted` is a text colour
 *   there, a background here) live inside the scope only.
 * - `html` and `body` rules are dropped: the page is the console's.
 * - The dark theme is dropped: the console has none, and a dark piece on a light page
 *   would be unreadable.
 */
export const SCOPE = ".legacy-html";
const PAGE = /^(html|body)(?![\w-])/;

/** Top-level blocks of a stylesheet: `[prelude, body]`, comments removed. */
export function blocks(css) {
  const text = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const found = [];
  let depth = 0;
  let start = 0;
  let open = 0;
  for (let index = 0; index < text.length; index += 1) {
    if (text[index] === "{") {
      if (depth === 0) {
        open = index;
      }
      depth += 1;
    } else if (text[index] === "}") {
      depth -= 1;
      if (depth === 0) {
        found.push([text.slice(start, open).trim(), text.slice(open + 1, index)]);
        start = index + 1;
      }
    }
  }
  return found;
}

function scopeSelector(selector) {
  const one = selector.trim();
  if (PAGE.test(one)) {
    return null;
  }
  return one.startsWith(":root") ? `${SCOPE}${one.slice(":root".length)}` : `${SCOPE} ${one}`;
}

function declarations(body) {
  return body
    .split(";")
    .map((line) => line.trim().replace(/\s+/g, " "))
    .filter(Boolean)
    .map((line) => `  ${line};`)
    .join("\n");
}

export function scopeLegacyCss(css) {
  const out = [];
  for (const [prelude, body] of blocks(css)) {
    if (prelude.startsWith("@media")) {
      if (prelude.includes("prefers-color-scheme")) {
        continue;
      }
      const inner = scopeLegacyCss(body);
      if (inner) {
        out.push(`${prelude} {\n${inner.replace(/^(?=.)/gm, "  ")}\n}`);
      }
    } else if (prelude.startsWith("@")) {
      // @keyframes, @font-face: not selectors.
      out.push(`${prelude} {${body.replace(/\s+/g, " ")}}`);
    } else {
      const selectors = prelude.split(",").map(scopeSelector).filter(Boolean);
      if (selectors.length) {
        out.push(`${selectors.join(",\n")} {\n${declarations(body)}\n}`);
      }
    }
  }
  return out.join("\n\n");
}

export const HEADER =
  "/* Generated by scripts/scope-legacy-css.mjs from src/static/local-ui.css: do not edit.\n" +
  "   `npm run generate:legacy-css` writes it again. */\n\n";

/** What the legacy pages take from the browser and from their own `body` rule, and the
 * console's reset takes away: the text's size, bold headings, paragraphs apart, underlined
 * links, bulleted lists. `:where` keeps these below every legacy rule. */
export const BASE = `${SCOPE} {
  color: var(--text);
  font-size: 13px;
  line-height: 1.45;
}

${SCOPE} :where(h1, h2, h3, h4, th, b, strong) {
  font-weight: bold;
}

${SCOPE} :where(h3) {
  margin: 1em 0;
  font-size: 1.17em;
}

${SCOPE} :where(p) {
  margin: 1em 0;
}

${SCOPE} :where(a) {
  text-decoration: underline;
}

${SCOPE} :where(ul, ol) {
  margin: 1em 0;
  padding-left: 40px;
  list-style: revert;
}

${SCOPE} :where(small) {
  font-size: smaller;
}

`;

async function main() {
  const css = await readFile("../src/static/local-ui.css", "utf8");
  await writeFile("src/legacy-html.css", `${HEADER}${BASE}${scopeLegacyCss(css)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
